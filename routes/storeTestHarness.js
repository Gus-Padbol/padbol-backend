export async function freshPgliteStore() {
  const pg = new PGlite();
  await applyStoreMigration(pg);
  const db = createRpcClient(pg);
  const server = await startStoreServer({ supabaseAdmin: db });
  return { pg, db, ...server, close: async () => { await server.close(); await pg.close(); } };
}

export async function request(baseUrl, method, path, { token = 'token-player', body, headers = {} } = {}) {
  const requestHeaders = { ...headers };
  if (token) requestHeaders.Authorization = `Bearer ${token}`;
  if (body !== undefined) requestHeaders['content-type'] = 'application/json';
  const response = await fetch(`${baseUrl}${path}`, {
    method,
    headers: requestHeaders,
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await response.text();
  let parsed = null;
  try { parsed = text ? JSON.parse(text) : null; } catch { parsed = text; }
  return { status: response.status, body: parsed, headers: response.headers };
}

