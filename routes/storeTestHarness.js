/**
 * Supabase-shaped `.rpc` adapter backed by PostgreSQL. It executes as
 * service_role inside a short transaction, mirroring the existing service-role
 * client; no pgPool is injected into the application routes. PGlite has one
 * session, so whole RPC calls are serialised there.
 */
export function createRpcClient(runner, { role = 'service_role' } = {}) {
  let tail = Promise.resolve();
  const direct = !runner.connect;

  const withClient = async (work) => {
    if (direct) {
      let releaseGate;
      const gate = new Promise((resolve) => { releaseGate = resolve; });
      const ahead = tail;
      tail = ahead.then(() => gate);
      await ahead;
      try { return await work(runner); } finally { releaseGate(); }
    }
    const client = await runner.connect();
    try { return await work(client); } finally { client.release?.(); }
  };

  return {
    async rpc(name, params = {}) {
      const keys = Object.keys(params);
      const values = keys.map((key) => {
        const value = params[key];
        return value !== null && typeof value === 'object' ? JSON.stringify(value) : value;
      });
      const args = keys.map((key, index) => `${key} => $${index + 1}`).join(', ');
      const sql = `SELECT public.${name}(${args}) AS data`;
      return withClient(async (client) => {
        try {
          await client.query('BEGIN');
          if (role) await client.query(`SET LOCAL ROLE ${role}`);
          const result = await client.query(sql, values);
          await client.query('COMMIT');
          return { data: result.rows[0]?.data ?? null, error: null };
        } catch (error) {
          try { await client.query('ROLLBACK'); } catch { /* best effort */ }
          return {
            data: null,
            error: {
              message: error?.message,
              code: error?.code,
              details: error?.detail,
              hint: error?.hint,
              constraint: error?.constraint,
            },
          };
        }
      });
    },
  };
}

export function buildStoreApp({ supabaseAdmin = {}, legacySuperAdminEmails = [] } = {}) {
  const app = express();
  app.use(express.json({ limit: '100kb' }));
  const getAuthenticatedUser = async (req) => {
    const token = String(req.headers.authorization || '').replace(/^Bearer\s+/i, '');
    const user = TOKENS[token];
    return user ? { user: { id: user.id, email: user.email }, status: 200 } : { user: null, status: 401, error: 'No autorizado' };
  };
  const deps = {
    getAuthenticatedUser,
    fetchUserRoleRowForAuthUser: async (user) => ROLE_ROWS[user.email] || null,
    legacySuperAdminEmails,
  };
  mountStoreSedeConfigRoutes(app, { supabaseAdmin, ...deps });
  mountStoreAdminRoutes(app, { supabaseAdmin, ...deps });
  mountStorePublicRoutes(app, { supabaseAdmin, getAuthenticatedUser });
  return app;
}

export async function listen(app) {
  const server = http.createServer(app);
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  return { server, baseUrl: `http://127.0.0.1:${server.address().port}` };
}

export async function startStoreServer(options = {}) {
  const { server, baseUrl } = await listen(buildStoreApp(options));
  return { server, baseUrl, close: () => new Promise((resolve) => server.close(resolve)) };
}

