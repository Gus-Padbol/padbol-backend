async function post(base, id, token, body) {
  const res = await fetch(`${base}/api/admin/nations-activation/events/nations-cup-napoli-2026/profile-requests/${id}/verify-age`, {
    method: 'POST',
    headers: {'Content-Type': 'application/json', ...(token ? {authorization: `Bearer ${token}`} : {})},
    body: JSON.stringify(body),
  });
  return {status: res.status, body: await res.json().catch(() => null)};
}

test('HTTP verify-age: auth server-side, 403, 422, idempotencia y conflicto', async () => {
  const f = await setup();
  try {
    assert.equal((await post(f.base, f.reqId, '', {verification_method: 'manual_roster', verification_reference: 'case-1'})).status, 401);
    assert.equal((await post(f.base, f.reqId, 'user', {verification_method: 'manual_roster', verification_reference: 'case-1'})).status, 403);
    assert.equal((await post(f.base, f.reqId, 'admin', {verification_method: 'manual_roster'})).status, 422);
    const first = await post(f.base, f.reqId, 'admin', {verification_method: 'manual_roster', verification_reference: 'case-1'});
    assert.equal(first.status, 200);
    assert.equal(first.body.idempotent, false);
    const second = await post(f.base, f.reqId, 'admin', {verification_method: 'manual_roster', verification_reference: 'case-1'});
    assert.equal(second.status, 200);
    assert.equal(second.body.idempotent, true);
  } finally {
    f.server.close();
    await f.db.close();
  }
  const c = await setup();
  try {
    assert.equal((await post(c.base, c.conflictId, 'admin', {verification_method: 'manual_roster', verification_reference: 'case-2'})).status, 409);
  } finally {
    c.server.close();
    await c.db.close();
  }
});
