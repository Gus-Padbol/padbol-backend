    const legacy = {request_id: 'legacy-req-0001', declared_name: 'Legacy Player', declared_country: 'IT', age_status: 'adulto', guardian_consent: false, profile_consent: true};
    const first = await svc.submit('nations-cup-napoli-2026', actor(A), legacy);
