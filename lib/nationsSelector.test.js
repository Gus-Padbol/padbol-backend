test('admin verifica edad unknown con evidencia; sin rol/evidencia o menor no actualiza; doble verify idempotente', async () => {
  const {db, pool, actor} = await fixture();
  try {
    const svc = createNationsProfileRequestsService({pool});
    const selection = selectionIdFor(57, UNKNOWN);
    const submitted = await svc.submit('nations-cup-napoli-2026', actor(A), {...body('req-verify'), selection_id: selection});
    assert.equal(submitted.selectionStatus, 'verificacion_pendiente');
    const row = (await db.query("select id from public.nations_profile_requests where request_id='req-verify-0001'")).rows[0];
    await assert.rejects(svc.verifyAge('nations-cup-napoli-2026', actor(A), row.id, {verification_method: 'manual_roster', verification_reference: 'case-1234'}), /FORBIDDEN/);
    await assert.rejects(svc.verifyAge('nations-cup-napoli-2026', actor(ADMIN), row.id, {verification_method: 'manual_roster'}), /VERIFICATION_EVIDENCE_REQUIRED/);
    const verified = await svc.verifyAge('nations-cup-napoli-2026', actor(ADMIN), row.id, {verification_method: 'manual_roster', verification_reference: 'case-1234'});
    assert.equal(verified.verified, true);
    assert.equal(verified.idempotent, false);
    const part = (await db.query('select age_status, minor from public.nations_activation_participants where participante_id=$1', [UNKNOWN])).rows[0];
    assert.deepEqual(part, {age_status: 'adulto', minor: false});
    const after = (await db.query('select age_status, age_verification_status, selection_status, status, age_verification_method, age_verification_reference, age_verified_by from public.nations_profile_requests where id=$1', [row.id])).rows[0];
    assert.equal(after.age_status, 'adulto');
    assert.equal(after.age_verification_status, 'verificada');
    assert.equal(after.selection_status, 'declarada');
    assert.equal(after.status, 'pendiente');
    assert.equal(after.age_verification_method, 'manual_roster');
    assert.equal(after.age_verification_reference, 'case-1234');
    assert.equal(after.age_verified_by, ADMIN);
    assert.equal((await db.query('select linked_user_id from public.torneo_participantes where id=$1', [UNKNOWN])).rows[0].linked_user_id, null);
    assert.equal((await db.query("select count(*)::int n from public.nations_activation_audit where action='age_verification'")).rows[0].n, 1);
    const retry = await svc.submit('nations-cup-napoli-2026', actor(A), {...body('req-verify'), selection_id: selection});
    assert.equal(retry.status, 'pendiente');
    const again = await svc.verifyAge('nations-cup-napoli-2026', actor(ADMIN), row.id, {verification_method: 'manual_roster', verification_reference: 'case-1234'});
    assert.equal(again.idempotent, true);
    await db.query("update public.nations_profile_requests set status='aprobada' where id=$1", [row.id]);
    const postApproval = await svc.verifyAge('nations-cup-napoli-2026', actor(ADMIN), row.id, {verification_method: 'manual_roster', verification_reference: 'case-1234'});
    assert.equal(postApproval.idempotent, true);
    assert.equal((await db.query("select count(*)::int n from public.nations_activation_audit where action='age_verification'")).rows[0].n, 1);

    const minorRow = (await db.query(`insert into public.nations_profile_requests(torneo_id,actor_user_id,request_id,declared_name,declared_country,age_status,guardian_consent,profile_consent,payload_hash,selected_participante_id,selection_status,age_verification_status)
      values(57,$1,'req-minor-verify-0001','Minor Real','IT','desconocido',false,true,'hash','${MINOR}','verificacion_pendiente','pendiente') returning id`, [C])).rows[0];
    await assert.rejects(svc.verifyAge('nations-cup-napoli-2026', actor(ADMIN), minorRow.id, {verification_method: 'manual_roster', verification_reference: 'case-9999'}), /MINOR_NOT_ELIGIBLE/);
    assert.equal((await db.query('select age_status from public.nations_activation_participants where participante_id=$1', [MINOR])).rows[0].age_status, 'menor');
  } finally { await db.close(); }
});


test('review bloquea aprobación de conflicto y mismatch selección/persona', async () => {
  const {db, pool, actor} = await fixture();
  try {
    const svc = createNationsProfileRequestsService({pool});
    const conflict = (await db.query(`insert into public.nations_profile_requests(torneo_id,actor_user_id,request_id,declared_name,declared_country,age_status,guardian_consent,profile_consent,payload_hash,selected_participante_id,selection_status,age_verification_status)
      values(57,$1,'review-conflict-0001','Adulto Real','IT','adulto',false,true,'h',$2,'en_conflicto','pendiente') returning id`, [C, ADULT])).rows[0];
    await assert.rejects(svc.review('nations-cup-napoli-2026', actor(ADMIN), conflict.id, {
      decision: 'aprobar', identity_verified: true, note: 'Revisión central con evidencia suficiente',
      matched_participante_id: ADULT,
    }), /SELECTION_CONFLICT/);
    assert.equal((await db.query('select linked_user_id from public.torneo_participantes where id=$1', [ADULT])).rows[0].linked_user_id, null);

    const mismatch = (await db.query(`insert into public.nations_profile_requests(torneo_id,actor_user_id,request_id,declared_name,declared_country,age_status,guardian_consent,profile_consent,payload_hash,selected_participante_id,selection_status,age_verification_status)
      values(57,$1,'review-mismatch-0001','Adulto Real','IT','adulto',false,true,'h',$2,'declarada','pendiente') returning id`, [B, ADULT])).rows[0];
    await assert.rejects(svc.review('nations-cup-napoli-2026', actor(ADMIN), mismatch.id, {
      decision: 'aprobar', identity_verified: true, note: 'Revisión central con evidencia suficiente',
      matched_participante_id: MINOR,
    }), /SELECTION_MISMATCH/);
    assert.equal((await db.query('select linked_user_id from public.torneo_participantes where id=$1', [ADULT])).rows[0].linked_user_id, null);
  } finally { await db.close(); }
});
