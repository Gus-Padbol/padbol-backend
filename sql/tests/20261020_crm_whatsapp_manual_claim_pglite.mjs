import { pathToFileURL } from 'node:url';
if (!process.env.PADBOL_PGLITE_MODULE) throw new Error('Set PADBOL_PGLITE_MODULE to the absolute PGlite module path.');
const { PGlite } = await import(pathToFileURL(process.env.PADBOL_PGLITE_MODULE).href);
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const db = new PGlite();
await db.exec(`create role anon; create role authenticated; create role service_role; create table public.crm_conversations(id uuid primary key,source_channel text not null); create table public.crm_replies(id uuid primary key,conversation_id uuid not null references public.crm_conversations,body text,operador text,status text); insert into crm_conversations values ('11111111-1111-4111-8111-111111111111','whatsapp'),('22222222-2222-4222-8222-222222222222','email');`);
const migration = await readFile('sql/20261020000000_crm_whatsapp_manual_claim.sql','utf8');
await db.exec(migration);
const call=(id,conv='11111111-1111-4111-8111-111111111111')=>db.query('select crm_claim_whatsapp_reply($1,$2,$3,$4) as result',[id,conv,'hi','operator']);
await db.exec("insert into crm_replies values ('dddddddd-dddd-4ddd-8ddd-dddddddddddd','11111111-1111-4111-8111-111111111111','draft','crm_funnel','pending')");
const a='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',b='bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
assert.equal((await call(a)).rows[0].result.created,true);
assert.equal((await call(a)).rows[0].result.created,false);
assert.equal((await call(b)).rows[0].result.blocked,true);
assert.equal((await db.query('select count(*)::int as n from crm_replies')).rows[0].n,2);
// Reapplying the migration must retain in-flight claims and the block.
await db.exec(migration);
assert.equal((await call(a)).rows[0].result.created,false);
assert.equal((await call(b)).rows[0].result.blocked,true);
assert.equal((await db.query('select count(*)::int as n from crm_whatsapp_manual_attempts')).rows[0].n,1);
await db.query("update crm_replies set status='sent' where id=$1",[a]);
assert.equal((await call(b)).rows[0].result.created,true);
await assert.rejects(()=>call('cccccccc-cccc-4ccc-8ccc-cccccccccccc','22222222-2222-4222-8222-222222222222'));
const privileges=await db.query("select has_function_privilege('anon','public.crm_claim_whatsapp_reply(uuid,uuid,text,text)','EXECUTE') as anon, has_function_privilege('service_role','public.crm_claim_whatsapp_reply(uuid,uuid,text,text)','EXECUTE') as service");
assert.deepEqual(privileges.rows[0],{anon:false,service:true});
const tablePrivileges=await db.query("select has_table_privilege('anon','public.crm_whatsapp_manual_attempts','SELECT') as anon, has_table_privilege('authenticated','public.crm_whatsapp_manual_attempts','INSERT') as authenticated, has_table_privilege('service_role','public.crm_whatsapp_manual_attempts','SELECT') as service");
assert.deepEqual(tablePrivileges.rows[0],{anon:false,authenticated:false,service:true});
await db.close();
console.log('Postgres-compatible PGlite SQL claim checks passed');
